import fs from "fs"
import path from "path"
import { slugifyFilePath as baseSlugifyFilePath, type FilePath } from "@quartz-community/utils"
import type { QuartzEmitterPlugin } from "../types"
import type { ProcessedContent } from "../vfile"
import { LEGACY_FOLDER_TO_SLUG } from "../../util/folder-map"

/**
 * Emits redirects for the old Persian URLs.
 *
 * The public URL scheme is English (`/pages/...`), but the content tree is an
 * Obsidian vault that keeps Persian folder names. Every page therefore has a
 * legacy Persian address that used to be indexed and shared.
 *
 * Two outputs are written:
 *
 *   1. `_redirects` — real 301s, used by hosts that understand it (Cloudflare
 *      Pages, Netlify).
 *   2. `<legacy path>/index.html` — a meta-refresh page. The blog is actually
 *      served by GitHub Pages, which ignores `_redirects`, so without these
 *      every legacy URL would 404. The stub keeps the canonical URL pointing at
 *      the real page, so search engines consolidate instead of indexing the
 *      stub as duplicate content.
 */

interface RedirectRule {
  from: string
  to: string
}

function joinPublicPath(slug: string): string {
  return encodeURI("/" + slug)
}

function collectRules(content: ProcessedContent[]) {
  const rules = new Map<string, RedirectRule>()
  const folders = new Set<string>()

  for (const [, file] of content) {
    const relativePath = file.data.relativePath as FilePath | undefined
    const slug = file.data.slug
    if (!relativePath || !slug) continue

    const legacySlug = baseSlugifyFilePath(relativePath)
    if (legacySlug !== slug) {
      const from = joinPublicPath(legacySlug)
      const to = joinPublicPath(slug)
      rules.set(from, { from, to })
      rules.set(`${from}/`, { from: `${from}/`, to: `${to}/` })
    }

    const folder = relativePath.split("/")[0]
    if (relativePath.includes("/") && LEGACY_FOLDER_TO_SLUG[folder]) {
      folders.add(folder)
    }
  }

  for (const folder of folders) {
    const mapped = LEGACY_FOLDER_TO_SLUG[folder]
    const from = joinPublicPath(folder)
    const to = joinPublicPath(mapped)
    rules.set(from, { from, to: `${to}/` })
    rules.set(`${from}/`, { from: `${from}/`, to: `${to}/` })
  }

  return [...rules.values()].sort((a, b) => a.from.localeCompare(b.from))
}

const escapeAttr = (value: string) =>
  value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;")

function stubHtml(to: string, canonical: string): string {
  const href = escapeAttr(to)
  const canonicalHref = escapeAttr(canonical)
  return `<!doctype html>
<html lang="fa" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>انتقال…</title>
<link rel="canonical" href="${canonicalHref}">
<meta http-equiv="refresh" content="0; url=${href}">
<script>location.replace(${JSON.stringify(to)})</script>
</head>
<body>
<p><a href="${href}">این صفحه جابه‌جا شده است — ادامه</a></p>
</body>
</html>
`
}

export const manifest = {
  name: "legacy-redirects",
  displayName: "Legacy Persian Redirects",
  description: "Emits 301 rules and meta-refresh stubs for the old Persian URLs.",
  version: "1.1.0",
  category: "emitter",
}

const LegacyRedirects: QuartzEmitterPlugin = () => ({
  name: "LegacyRedirects",
  async *emit({ argv, cfg }, content) {
    const rules = collectRules(content)
    if (rules.length === 0) return

    const baseUrl = cfg.configuration.baseUrl ? `https://${cfg.configuration.baseUrl}` : ""
    const outputPath = path.join(argv.output, "_redirects")
    const body =
      "# Generated by quartz/plugins/legacy-redirects — do not edit by hand.\n" +
      rules.map((rule) => `${rule.from} ${rule.to} 301`).join("\n") +
      "\n"

    await fs.promises.mkdir(path.dirname(outputPath), { recursive: true })
    await fs.promises.writeFile(outputPath, body, "utf8")
    yield outputPath as FilePath

    // One stub per directory. `from` and `from/` resolve to the same folder, so
    // key on the decoded path without its trailing slash. The bare rule wins:
    // its target has no trailing slash (`/pages/about`), which is how Quartz
    // emits and links single pages (`pages/about.html`). Keeping the `from/`
    // variant instead would point the stub at `/pages/about/`, which does not
    // exist and would 404 on a static host.
    const stubs = new Map<string, RedirectRule>()
    for (const rule of rules) {
      let decoded: string
      try {
        decoded = decodeURIComponent(rule.from)
      } catch {
        continue
      }
      const key = decoded.replace(/\/+$/, "")
      if (!stubs.has(key)) stubs.set(key, rule)
    }

    for (const [decodedPath, rule] of stubs) {
      // Slugs are generated by Quartz, but keep the write inside output anyway.
      const target = path.resolve(argv.output, "." + decodedPath)
      const root = path.resolve(argv.output)
      if (target !== root && !target.startsWith(root + path.sep)) continue

      const filePath = path.join(target, "index.html")
      await fs.promises.mkdir(target, { recursive: true })
      await fs.promises.writeFile(filePath, stubHtml(rule.to, baseUrl + rule.to), "utf8")
      yield filePath as FilePath
    }
  },
})

export default LegacyRedirects